-- Schema for Spring Data JDBC. Runs at every start-up (spring.sql.init.mode=always) and only
-- creates what is missing, so it is safe on the existing PostgreSQL database: the first four
-- tables keep the exact names and columns Hibernate created before the move to Spring Data JDBC.
-- The SQL is portable between PostgreSQL (production) and HSQLDB (local runs and tests).

CREATE TABLE IF NOT EXISTS app_user (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(60)  NOT NULL UNIQUE,
    password          VARCHAR(255) NOT NULL,
    display_name      VARCHAR(80),
    role              VARCHAR(20)  NOT NULL,
    api_key_encrypted VARCHAR(1024),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS conversation (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id),
    title      VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT        NOT NULL REFERENCES conversation (id),
    role            VARCHAR(16)   NOT NULL,
    content         VARCHAR(8000) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS memory (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id),
    content    VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Private document library (new in this version). Owner 'public' is the bundled sample.
CREATE TABLE IF NOT EXISTS knowledge_document (
    id          VARCHAR(36)  PRIMARY KEY,
    owner       VARCHAR(60)  NOT NULL,
    filename    VARCHAR(255) NOT NULL,
    file_type   VARCHAR(20)  NOT NULL,
    size_bytes  BIGINT       NOT NULL,
    pages       INTEGER,
    characters  INTEGER      NOT NULL,
    chunk_count INTEGER      NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    indexed_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS document_chunk (
    document_id VARCHAR(36)   NOT NULL REFERENCES knowledge_document (id) ON DELETE CASCADE,
    chunk_index INTEGER       NOT NULL,
    chunk_position INTEGER    NOT NULL,
    page_number INTEGER,
    chunk_text  VARCHAR(4000) NOT NULL,
    vector_id   VARCHAR(36),
    PRIMARY KEY (document_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS idx_knowledge_document_owner ON knowledge_document (owner);
CREATE INDEX IF NOT EXISTS idx_conversation_user ON conversation (user_id);
CREATE INDEX IF NOT EXISTS idx_chat_message_conversation ON chat_message (conversation_id);
CREATE INDEX IF NOT EXISTS idx_memory_user ON memory (user_id);
